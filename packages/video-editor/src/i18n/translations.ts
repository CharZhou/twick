export type TwickLocale = keyof typeof translations;
export type TwickLanguagePreference = "auto" | TwickLocale;
export type TwickTranslationKey = keyof typeof translations.en;

type TranslationParams = Record<string, string | number>;

export const TWICK_LANGUAGE_OPTIONS: TwickLanguagePreference[] = [
  "auto",
  "en",
  "zh",
];

export function normalizeTwickLocale(language?: string | null): TwickLocale {
  const normalized = language?.toLowerCase() ?? "";
  if (normalized.startsWith("zh")) {
    return "zh";
  }

  return "en";
}

export function resolveTwickLocale(
  preference: TwickLanguagePreference,
  browserLanguage?: string | null,
): TwickLocale {
  if (preference === "auto") {
    return normalizeTwickLocale(browserLanguage);
  }

  return preference;
}

export function formatTwickMessage(
  template: string,
  params?: TranslationParams,
): string {
  if (!params) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    params[key] === undefined ? `{${key}}` : String(params[key]),
  );
}

export function translateTwickText(
  language: TwickLocale,
  key: TwickTranslationKey,
  params?: TranslationParams,
): string {
  const template = translations[language][key] ?? translations.en[key] ?? key;
  return formatTwickMessage(template, params);
}

export function getStoredTwickLanguagePreference(
  storageKey = TWICK_LANGUAGE_STORAGE_KEY,
): TwickLanguagePreference {
  if (typeof window === "undefined") {
    return "auto";
  }

  const stored = window.localStorage.getItem(storageKey);
  if (stored === "auto" || stored === "en" || stored === "zh") {
    return stored;
  }

  return "auto";
}

export function getCurrentTwickLocale(
  storageKey = TWICK_LANGUAGE_STORAGE_KEY,
): TwickLocale {
  const preference = getStoredTwickLanguagePreference(storageKey);
  const browserLanguage =
    typeof window === "undefined" ? undefined : window.navigator?.language;

  return resolveTwickLocale(preference, browserLanguage);
}
